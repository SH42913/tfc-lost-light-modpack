// Rebuilds the CurseForge export selection (`export.filesSelection` in user-prefs.json)
// from the files currently on disk, so nothing new is forgotten and no junk gets exported.
//
//   node tools/export/sync.js .          — rewrite user-prefs.json, print what changed
//   node tools/export/sync.js . --check  — only print what would change
//
// CurseForge keeps a snapshot of the instance tree with a flag per path; files that appeared
// after the last export are missing from it. Here every path on disk is listed (except .git)
// and the flag comes from the rules below. A folder is selected only if everything in it is.
// Other fields of user-prefs.json (recommendedRam, install, ...) are kept as is.

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const root = path.resolve(process.argv[2] || '.');
const CHECK = process.argv.includes('--check');
const USER_PREFS = path.join(root, 'user-prefs.json');
const SEP = '\\';

// ---- Rules (paths use '/', relative to the instance root) ----

// Whole folders/files that go into the export.
const INCLUDE = [
  'config', 'defaultconfigs', 'kubejs', 'mods', 'tfc_structures_datapacks',
  'LICENSE', 'README.md',
];

// Excluded inside INCLUDE (regexps against the relative path).
const EXCLUDE = [
  /^kubejs\/probe(\/|$)/,              // ProbeJS typings and dumps
  /^kubejs\/documentation(\/|$)/,      // generated by KubeJS
  /^kubejs\/README\.txt$/,             // generated by KubeJS
  /^mods\/\.connector(\/|$)/,          // Sinytra Connector cache
  /^mods\/[^/]+\//,                    // only jars directly in mods/ (stray folders like mods/data are junk)
  /^tfc_structures_datapacks\/tfc_structures_main(\/|$)/, // third-party, not ours to ship
  /^config\/inventory-particles\/cache(\/|$)/,
  /^config\/inventoryprofilesnext\/[^/]+\//, // per-world/server profiles (folders)
  /^config\/jei\/world(\/|$)/,         // per-world JEI state
  /^config\/crash_assistant\/modlist\.json$/, // rewritten on every launch
  /^config\/fast_travel_waypoints\/[^/]+\.(applied|completed)$/, // per-install migration markers
  /\.bak$/,
  /\.backup\d*$/,
];

// resourcepacks/: only packs enabled by default (config/resourcepackoverrides.json, see tools/packs/sync.js).
function resourcePacks() {
  const o = JSON.parse(fs.readFileSync(path.join(root, 'config/resourcepackoverrides.json'), 'utf8'));
  return new Set(o.default_packs.filter(p => p.startsWith('file/')).map(p => 'resourcepacks/' + p.slice(5)));
}
// shaderpacks/: only the shader zips themselves (unpacked/patched folders are made by Euphoria Patcher).
const isShaderPack = rel => /^shaderpacks\/[^/]+\.zip$/.test(rel);

// ---- Walk ----

const packs = resourcePacks();

function fileSelected(rel) {
  if (rel.startsWith('resourcepacks/')) return packs.has(rel);
  if (rel.startsWith('shaderpacks/')) return isShaderPack(rel);
  if (!INCLUDE.some(i => rel === i || rel.startsWith(i + '/'))) return false;
  return !EXCLUDE.some(r => r.test(rel));
}

const cmp = (a, b) => {
  const x = a.toLowerCase(), y = b.toLowerCase();
  return x < y ? -1 : x > y ? 1 : (a < b ? -1 : a > b ? 1 : 0);
};

const entries = [];      // { path, isSelected } in CurseForge order: folder, its subfolders, then its files
const selectedFiles = [];

// Returns whether everything inside `dir` is selected.
function walk(dirRel) {
  const abs = path.join(root, dirRel);
  const items = fs.readdirSync(abs, { withFileTypes: true });
  const dirs = items.filter(d => d.isDirectory()).map(d => d.name).sort(cmp);
  const files = items.filter(d => !d.isDirectory()).map(d => d.name).sort(cmp);
  // An empty folder is selected when a file in it would be.
  if (!dirs.length && !files.length) return fileSelected(dirRel + '/x');
  let all = true;
  for (const name of dirs) {
    const rel = dirRel ? dirRel + '/' + name : name;
    if (rel === '.git') continue;
    const at = entries.length;
    entries.push(null);
    const sel = walk(rel);
    entries[at] = { path: rel.split('/').join(SEP), isSelected: sel };
    all = all && sel;
  }
  for (const name of files) {
    const rel = dirRel ? dirRel + '/' + name : name;
    const sel = fileSelected(rel);
    entries.push({ path: rel.split('/').join(SEP), isSelected: sel });
    if (sel) selectedFiles.push(rel);
    all = all && sel;
  }
  return all;
}
walk('');

// ---- Checks ----

const warn = [];
for (const p of packs) if (!fs.existsSync(path.join(root, p))) warn.push(`default pack missing on disk: ${p}`);
for (const f of fs.readdirSync(path.join(root, 'resourcepacks')))
  if (!packs.has('resourcepacks/' + f)) warn.push(`resourcepack not exported (not in default_packs): resourcepacks/${f}`);
const disabled = fs.readdirSync(path.join(root, 'mods')).filter(f => f.endsWith('.disabled'));
if (disabled.length) warn.push(`exported as disabled (${disabled.length}): ${disabled.join(', ')}`);
for (const d of fs.readdirSync(path.join(root, 'mods'), { withFileTypes: true }))
  if (d.isDirectory() && d.name !== '.connector') warn.push(`stray folder not exported: mods/${d.name}/`);

// Exported CurseForge addons whose project/file looks gone from CurseForge. The export writes them into
// manifest.json by projectID/fileID, and CurseForge rejects the upload ("References invalid fileIDs").
// Signs in minecraftinstance.json (refreshed by the CurseForge app, so may lag behind the site):
// the name became a `project-<id>` placeholder, the file is marked unavailable, or a status is not Approved (4).
try {
  const mi = JSON.parse(fs.readFileSync(path.join(root, 'minecraftinstance.json'), 'utf8').replace(/^﻿/, ''));
  const exported = new Set(selectedFiles.map(f => f.toLowerCase()));
  for (const a of mi.installedAddons || []) {
    const f = a.installedFile || {};
    const disk = a.fileNameOnDisk || f.fileNameOnDisk || f.fileName;
    if (!disk || !a.modFolderPath) continue;
    const rel = path.relative(root, path.join(a.modFolderPath, disk)).split(path.sep).join('/');
    if (!exported.has(rel.toLowerCase())) continue;
    const why = [];
    if (/^project-\d+$/.test(a.name)) why.push('project name is a placeholder');
    if (f.isAvailable === false) why.push('file unavailable');
    if (f.fileStatus != null && f.fileStatus !== 4) why.push(`fileStatus ${f.fileStatus}`);
    if (f.projectStatus != null && f.projectStatus !== 4) why.push(`projectStatus ${f.projectStatus}`);
    if (why.length) warn.push(`possibly removed from CurseForge (${why.join(', ')}): ${rel} — "${a.name}", projectID ${a.addonID}, fileID ${f.id}`);
  }
} catch (e) { warn.push(`minecraftinstance.json not readable, skipped the CurseForge availability check: ${e.message}`); }

// Selected sources that git does not know about (forgot to commit?). mods/resourcepacks are git-ignored by design.
try {
  const tracked = new Set(execSync('git ls-files -z', { cwd: root, maxBuffer: 64 << 20 })
    .toString('utf8').split('\0').filter(Boolean));
  for (const f of selectedFiles)
    if (!tracked.has(f) && !/^(mods|resourcepacks)\//.test(f)) warn.push(`selected but not in git: ${f}`);
} catch { warn.push('git not available, skipped the git check'); }

// ---- Diff & write ----

const raw = fs.readFileSync(USER_PREFS, 'utf8');
const prefs = JSON.parse(raw);
const before = new Map(prefs.export.filesSelection.map(e => [e.path, e.isSelected]));
const isFile = e => !fs.statSync(path.join(root, e.path.split(SEP).join('/'))).isDirectory();
const added = [], removed = [];
for (const e of entries) {
  if (!isFile(e)) continue;
  const was = before.get(e.path) === true;
  if (e.isSelected && !was) added.push(e.path);
  if (!e.isSelected && was) removed.push(e.path);
}
const gone = prefs.export.filesSelection.filter(e => e.isSelected && !fs.existsSync(path.join(root, e.path.split(SEP).join('/'))));

const summarize = (title, list) => {
  if (!list.length) return;
  // group by first two path levels to keep the output short
  const g = new Map();
  for (const p of list) { const k = p.split(SEP).slice(0, 2).join(SEP); g.set(k, (g.get(k) || 0) + 1); }
  console.log(`${title}: ${list.length}`);
  for (const [k, n] of [...g].sort((a, b) => cmp(a[0], b[0]))) console.log(`  ${k}${n > 1 ? `  (${n})` : ''}`);
};
summarize('Newly selected files', added);
summarize('No longer selected files', removed);
summarize('Selected before, gone from disk', gone.map(e => e.path));
if (warn.length) { console.log('Warnings:'); warn.forEach(w => console.log('  ' + w)); }
console.log(`Total: ${entries.length} paths, ${selectedFiles.length} files selected.`);

if (CHECK) { console.log('--check: user-prefs.json not written.'); process.exit(0); }

prefs.export.filesSelection = entries;
const eol = raw.includes('\r\n') ? '\r\n' : '\n';
fs.writeFileSync(USER_PREFS, JSON.stringify(prefs, null, 2).replace(/\n/g, eol));
console.log('user-prefs.json written.');
